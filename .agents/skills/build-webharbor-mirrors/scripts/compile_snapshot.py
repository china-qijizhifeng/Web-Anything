def is_noninteractive_inline_script(source: str) -> bool:
    """Recognize inert framework data, telemetry, and a visual SVG polyfill."""
    if re.fullmatch(r"\s*svg4everybody\s*\(\s*\)\s*;?\s*", source):
        return True
    if is_next_flight_data_script(source):
        return True
    folded = source.casefold()
    return (
        (
            "window.datalayer" in folded
            and "function gtag" in folded
            and "gtag(" in folded
            and "config" in folded
        )
        or (
            "googletagmanager.com/gtm.js" in folded
            and "gtm.start" in folded
            and "datalayer" in folded
        )
    )


def is_next_flight_data_script(source: str) -> bool:
    """Accept only JSON-valued Next.js Flight queue pushes, never executable payloads."""
    remaining = source.strip()
    if not remaining:
        return False

    bootstrap = "(self.__next_f=self.__next_f||[]).push("
    push = "self.__next_f.push("
    saw_push = False
    while remaining:
        prefix = bootstrap if not saw_push and remaining.startswith(bootstrap) else push
        if not remaining.startswith(prefix):
            return False
        try:
            payload, end = json.JSONDecoder().raw_decode(remaining, len(prefix))
        except json.JSONDecodeError:
            return False
        if (
            not isinstance(payload, list)
            or not payload
            or payload[0] not in {0, 1, 2}
            or remaining[end : end + 1] != ")"
        ):
            return False
        remaining = remaining[end + 1 :].lstrip()
        if remaining.startswith(";"):
            remaining = remaining[1:].lstrip()
        saw_push = True
    return saw_push


def presentation_event_kind(tag: str, name: str, value: str | None) -> str | None:
    """Recognize exact image-load handlers whose final state is presentation only."""
    if tag != "img" or name.casefold() != "onload" or not isinstance(value, str):
        return None
    compact = re.sub(r"\s+", "", value).rstrip(";")
    if compact in {"this.style.opacity='1'", 'this.style.opacity="1"'}:
        return "image_opacity"
    if compact in {
        "this.parentNode.dataset.loaded='true'",
        'this.parentNode.dataset.loaded="true"',
    }:
        return "parent_loaded"
    return None


