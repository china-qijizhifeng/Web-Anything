def is_safe_inline_dom_initializer(source: str) -> bool:
    """Accept only bounded, static DOM state initialization statements."""
    if not source.strip() or len(source.encode("utf-8")) > 4096:
        return False
    statements = [statement.strip() for statement in source.split(";") if statement.strip()]
    return bool(statements) and all(
        any(pattern.fullmatch(statement) for pattern in SAFE_DOM_INITIALIZER_PATTERNS)
        for statement in statements
    )


def is_safe_locale_route_redirect(source: str) -> bool:
    """Accept a fixed local-only locale redirect over an explicit route allowlist."""
    compact = re.sub(r"\s+", "", source)
    route = r'"(?:/|/[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*)":1'
    pattern = (
        r"^\(function\(\)\{varwhitelist=\{"
        + route
        + r"(?:,"
        + route
        + r")*\}varp=location\.pathname"
        r"varnormalized=p\.length>1&&p\.charAt\(p\.length-1\)==='/'\?p\.slice\(0,-1\):p"
        r"if\(normalized===''\)\{normalized='/'\}"
        r"if\(whitelist\[normalized\]&&document\.cookie\.indexOf\('NEXT_LOCALE=en'\)!==-1\)\{"
        r"vartarget=normalized==='/'\?'/en/':'/en'\+normalized\+'/'"
        r"location\.replace\(target\+location\.search\+location\.hash\)\}\}\)\(\);?$"
    )
    return re.fullmatch(pattern, compact) is not None


