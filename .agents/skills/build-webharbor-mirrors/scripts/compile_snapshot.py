def remove_legacy_generated_paths(site_dir: Path) -> list[str]:
    removed = []
    for relative in (
        Path("_health.py"),
        Path("templates"),
        Path("static/css"),
        Path("static/js"),
        Path("static/icons"),
        Path("static/images"),
    ):
        path = site_dir / relative
        if not path.exists() and not path.is_symlink():
            continue
