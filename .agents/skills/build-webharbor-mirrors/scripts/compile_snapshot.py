@dataclass
class RewriteMaps:
    source_url: str
    page_hosts: frozenset[str]
    assets: dict[str, str]
    executable_scripts: frozenset[str] = frozenset()

    def normalize(self, raw: str) -> str | None:
        return normalize_url(self.source_url, html.unescape(raw))

    def same_page_host(self, url: str) -> bool:
        return (urlsplit(url).hostname or "") in self.page_hosts

    def asset_path(self, url: str) -> str | None:
        key = self.assets.get(url)
        return f"/__webharbor_asset/{key}" if key else None


