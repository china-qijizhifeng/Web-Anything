def css_hides_body(body: bytes) -> bool:
    text = body.decode("utf-8", errors="replace")
    return any(
        BODY_HIDDEN_DECLARATION_RE.search(declarations)
        for declarations in BODY_CSS_RULE_RE.findall(text)
    )


class PageSummaryParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.h1: list[str] = []
        self.headings: list[str] = []
        self.identity_names: list[str] = []
        self._capture: str | None = None
        self._parts: list[str] = []
        self._jsonld_depth = 0
        self._jsonld_parts: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        values = {key.lower(): value or "" for key, value in attrs}
        if tag.lower() == "script" and values.get("type", "").casefold() == "application/ld+json":
            self._jsonld_depth += 1
            self._jsonld_parts = []
        if tag.lower() in {"title", "h1", "h2", "h3"}:
            self._capture = tag.lower()
            self._parts = []

    def handle_data(self, data: str) -> None:
        if self._jsonld_depth:
            self._jsonld_parts.append(data)
        if self._capture:
            self._parts.append(data)

    def handle_endtag(self, tag: str) -> None:
        if tag.lower() == "script" and self._jsonld_depth:
            self._jsonld_depth -= 1
            if not self._jsonld_depth:
                try:
                    value = json.loads("".join(self._jsonld_parts))
                except json.JSONDecodeError:
                    value = None
                self.identity_names.extend(jsonld_identity_names(value))
                self._jsonld_parts = []
        if self._capture != tag.lower():
            return
        value = " ".join("".join(self._parts).split())
        if value:
            if self._capture == "title" and not self.title:
                self.title = value
            elif self._capture == "h1":
                self.h1.append(value)
                self.headings.append(value)
            else:
                self.headings.append(value)
        self._capture = None
        self._parts = []


def jsonld_identity_names(value: Any) -> list[str]:
    names: list[str] = []
    if isinstance(value, list):
        for item in value:
            names.extend(jsonld_identity_names(item))
        return names
    if not isinstance(value, dict):
        return names
    raw_types = value.get("@type", [])
    if isinstance(raw_types, str):
        types = {raw_types}
    elif isinstance(raw_types, list):
        types = {item for item in raw_types if isinstance(item, str)}
    else:
        types = set()
    if types & {"WebSite", "Organization", "GovernmentOrganization", "GovernmentOffice"}:
        name = value.get("name")
        if isinstance(name, str) and 2 <= len(name.strip()) <= 100:
            names.append(name.strip())
    for key in ("@graph", "publisher", "provider"):
        names.extend(jsonld_identity_names(value.get(key)))
    return names


def rewrite_css(body: bytes, source_url: str, asset_urls: dict[str, str]) -> tuple[bytes, int]:
    text = body.decode("utf-8", errors="replace")
    missing = 0

    def replacement(raw: str) -> str:
        nonlocal missing
        if raw.strip().startswith(("data:", "blob:", "#")):
            return raw
        normalized = normalize_url(source_url, raw)
        key = asset_urls.get(normalized or "")
        if key:
            return f"/__webharbor_asset/{key}"
        missing += 1
        return "/__webharbor_missing_asset"

    def replace_url(match: re.Match[str]) -> str:
        quote_char, raw = match.groups()
        return f"url({quote_char}{replacement(raw)}{quote_char})"

    def replace_import(match: re.Match[str]) -> str:
        prefix, quote_char, raw = match.groups()
        return f"{prefix}{quote_char}{replacement(raw)}{quote_char}"

    text = CSS_URL_RE.sub(replace_url, text)
    text = CSS_IMPORT_RE.sub(replace_import, text)
    return text.encode("utf-8"), missing


def rewrite_script_asset_literals(
    body: bytes, source_url: str, asset_urls: dict[str, str]
) -> tuple[bytes, int]:
    """Localize only exact quoted URLs whose captured asset bytes are known."""
    text = body.decode("utf-8", errors="replace")
    rewritten = 0

    def replace(match: re.Match[str]) -> str:
        nonlocal rewritten
        try:
            normalized = normalize_url(source_url, match.group("url"))
        except ValueError:
            return match.group(0)
        key = asset_urls.get(normalized or "")
        if not key:
            return match.group(0)
        rewritten += 1
        quote_char = match.group("quote")
        return f"{quote_char}/__webharbor_asset/{key}{quote_char}"

    return STATIC_SCRIPT_ASSET_LITERAL_RE.sub(replace, text).encode("utf-8"), rewritten


def apply_pinned_script_rewrites(
    body: bytes, rewrites: list[dict[str, Any]]
) -> tuple[bytes, int]:
    """Apply exact, hash-gated local endpoint rewrites declared by a site config."""
    text = body.decode("utf-8", errors="strict")
    rewritten = 0
    for rewrite in rewrites:
        old = rewrite["old"]
        expected_count = rewrite["expected_count"]
        missing_literals = [
            literal for literal in rewrite["required_literals"] if literal not in text
        ]
        if missing_literals:
            raise CompileError(
                f"source script rewrite {rewrite['id']} is missing grounded semantics"
            )
        actual_count = text.count(old)
        if actual_count != expected_count:
            raise CompileError(
                f"source script rewrite {rewrite['id']} expected {expected_count} "
                f"matches, found {actual_count}"
            )
        text = text.replace(old, rewrite["new"])
        rewritten += actual_count
    return text.encode("utf-8"), rewritten


def deterministic_gzip_json(value: dict[str, Any]) -> bytes:
    raw = json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")
    output = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=output, mtime=0) as archive:
        archive.write(raw)
    return output.getvalue()


def display_name_from_pages(pages: list[dict[str, Any]], fallback: str) -> str:
    if pages and pages[0].get("identity_names"):
        return pages[0]["identity_names"][0]
    if pages and pages[0].get("title"):
        title = pages[0]["title"]
        for separator in (" | ", " - ", " — ", " :: "):
            if separator in title:
                parts = [part.strip() for part in title.split(separator) if part.strip()]
                if parts:
                    return parts[-1] if len(parts[-1]) >= 3 else parts[0]
        if len(title) <= 80:
            return title
    return fallback.replace("_", " ").title()


